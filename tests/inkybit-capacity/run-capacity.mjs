import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { performance } from "node:perf_hooks";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const fixtureRoot = resolve(root, "tests/inkybit-capacity");
const work = resolve(fixtureRoot, ".work");
const toolchain = JSON.parse(readFileSync(resolve(root, "inkybit-toolchain.json"), "utf8"));
const commit = toolchain.extension.commit;
const counts = process.argv.includes("--quick") ? [1, 2, 4, 8] : [1, 2, 4, 8, 64];

function makeImage(seed) {
    const pixels = new Uint8Array(250 * 120);
    let state = (seed + 1) >>> 0;
    for (let i = 0; i < pixels.length; i++) {
        state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
        pixels[i] = state % 3;
    }
    const bytes = new Uint8Array(7510);
    bytes.set([0x49, 0x42, 0x49, 0x54, 1, 1, 250, 0, 120, 0]);
    for (let i = 0; i < pixels.length; i++) {
        bytes[10 + (i >> 2)] |= pixels[i] << (6 - 2 * (i & 3));
    }
    return bytes;
}

function literal(bytes) {
    return "hex`" + Array.from(bytes, byte => byte.toString(16).padStart(2, "0")).join("") + "`";
}

function mainSource(count) {
    const lines = ["// Generated by run-capacity.mjs; every image is byte-distinct."];
    for (let i = 0; i < count; i++) lines.push(`const image${i} = ${literal(makeImage(i))}`);
    for (let i = 0; i < count; i++) lines.push(`inkybit.drawFullScreenImage(image${i})`);
    return lines.join("\n") + "\n";
}

function parseAsm() {
    const asm = readFileSync(resolve(work, "built/mbcodal-binary.asm"), "utf8");
    const generated = asm.match(/generated code sizes \(bytes\): (\d+).*src size (\d+)/);
    const total = asm.match(/total bytes: (\d+).*with (\d+) free/);
    return {
        generatedBytes: generated ? Number(generated[1]) : null,
        compilerSourceBytes: generated ? Number(generated[2]) : null,
        totalFlashBytes: total ? Number(total[1]) : null,
        freeFlashBytes: total ? Number(total[2]) : null
    };
}

rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });
writeFileSync(resolve(work, "pxt.json"), JSON.stringify({
    name: "inkybit-capacity-generated",
    description: "Generated Ticket 05 capacity fixture",
    dependencies: {
        core: "file:../../../libs/core",
        inkybit: `github:enricoconductive/cm-inkybit#${commit}`,
        microphone: "*"
    },
    files: ["main.ts"]
}, null, 4) + "\n");
writeFileSync(resolve(work, "main.ts"), mainSource(1));

let command = spawnSync(resolve(root, "node_modules/.bin/pxt"), ["install"], {
    cwd: work, encoding: "utf8", timeout: 300000
});
if (command.status !== 0) throw new Error(command.stdout + command.stderr);

const results = [];
for (const count of counts) {
    const source = mainSource(count);
    writeFileSync(resolve(work, "main.ts"), source);
    rmSync(resolve(work, "built"), { recursive: true, force: true });
    const started = performance.now();
    command = spawnSync(resolve(root, "node_modules/.bin/pxt"), ["build"], {
        cwd: work, encoding: "utf8", timeout: 600000
    });
    const elapsedMs = Math.round(performance.now() - started);
    const output = (command.stdout + command.stderr).trim();
    const result = {
        imageCount: count,
        sourceBytes: Buffer.byteLength(source),
        compileSucceeded: command.status === 0,
        compileMs: elapsedMs,
        diagnostic: command.status === 0 ? "" : output.split("\n").slice(-8).join("\n")
    };
    if (result.compileSucceeded) Object.assign(result, parseAsm());
    results.push(result);
    console.log(`${count} image(s): ${result.compileSucceeded ? "PASS" : "FAIL"}, ${result.sourceBytes} source bytes, ${elapsedMs} ms`);
}

for (let i = 1; i < results.length; i++) {
    const current = results[i];
    const previous = results[i - 1];
    if (current.compileSucceeded && previous.compileSucceeded) {
        current.incrementalFlashBytes = current.totalFlashBytes - previous.totalFlashBytes;
        current.incrementalImages = current.imageCount - previous.imageCount;
    }
}

const evidence = {
    generatedAt: new Date().toISOString(),
    node: process.version,
    targetCommit: toolchain.target.upstreamCommit,
    extensionCommit: commit,
    results
};
mkdirSync(resolve(fixtureRoot, "results"), { recursive: true });
writeFileSync(resolve(fixtureRoot, "results/latest.json"), JSON.stringify(evidence, null, 2) + "\n");

const four = results.find(result => result.imageCount === 4);
if (!four?.compileSucceeded) throw new Error("four-image product gate failed; investigate named assets");
const oversized = results.find(result => result.imageCount === 64);
if (oversized && oversized.compileSucceeded) {
    throw new Error("64-image oversized diagnostic gate did not fail as expected");
}
